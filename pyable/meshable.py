"""
VTK / SimpleITK conversion and ParaView export utilities for pyable.

This module provides:

- vtk2sitk:
    Convert vtkImageData into a SimpleITK image.

- sitk2vtk:
    Convert a 2D or 3D SimpleITK image into vtkImageData.

- sitk_to_structured_grid:
    Export scalar, vector, or tensor images as coordinate-aware
    vtkStructuredGrid objects.

- binary_mask_to_polydata:
    Convert a binary SimpleITK mask into a surface mesh.

- label_map_to_multiblock:
    Convert a multi-label segmentation into a VTK multiblock dataset,
    with one surface per label.

- write_vtk_dataset:
    Write .vts, .vtp, or .vtm files for ParaView.

Supported coordinate systems:

- "lps":
    Native SimpleITK physical coordinates.

- "ras":
    NIfTI-style RAS physical coordinates.

- "fsl":
    FSL scaled-voxel coordinates, useful when displaying images together
    with meshes generated by FSL tools.

- "index":
    Raw voxel indices.
"""

from __future__ import annotations

from pathlib import Path
from typing import Iterable, Optional, Sequence

import numpy as np
import SimpleITK as sitk
import vtk
import vtk.util.numpy_support as vtknp
from vtk.util import numpy_support


# =============================================================================
# BASIC VTK <-> SIMPLEITK CONVERSION
# =============================================================================


def vtk2sitk(vtkimg: vtk.vtkImageData, debug: bool = False) -> sitk.Image:
    """
    Convert vtkImageData into a SimpleITK image.

    Scalar and multi-component VTK images are supported.

    Parameters
    ----------
    vtkimg:
        Input vtkImageData.
    debug:
        Print conversion details.

    Returns
    -------
    sitk.Image
        Converted SimpleITK image.
    """
    if not isinstance(vtkimg, vtk.vtkImageData):
        raise TypeError("vtk2sitk expects a vtkImageData object.")

    vtk_data = vtkimg.GetPointData().GetScalars()

    if vtk_data is None:
        vtk_data = vtkimg.GetPointData().GetVectors()

    if vtk_data is None:
        vtk_data = vtkimg.GetPointData().GetTensors()

    if vtk_data is None:
        raise ValueError(
            "VTK image has no active scalars, vectors, or tensors."
        )

    npdata = vtknp.vtk_to_numpy(vtk_data)

    nx, ny, nz = vtkimg.GetDimensions()
    ncomp = vtk_data.GetNumberOfComponents()

    if ncomp == 1:
        array = npdata.reshape((nz, ny, nx), order="C")
        sitkimg = sitk.GetImageFromArray(array, isVector=False)
    else:
        array = npdata.reshape((nz, ny, nx, ncomp), order="C")
        sitkimg = sitk.GetImageFromArray(array, isVector=True)

    sitkimg.SetSpacing(tuple(float(v) for v in vtkimg.GetSpacing()))
    sitkimg.SetOrigin(tuple(float(v) for v in vtkimg.GetOrigin()))

    if vtk.vtkVersion.GetVTKMajorVersion() >= 9:
        matrix = vtkimg.GetDirectionMatrix()

        if matrix is not None:
            direction = tuple(
                float(matrix.GetElement(row, col))
                for row in range(3)
                for col in range(3)
            )
            sitkimg.SetDirection(direction)

    if debug:
        print("VTK dimensions:", (nx, ny, nz))
        print("VTK components:", ncomp)
        print("NumPy shape:", npdata.shape)
        print("SimpleITK size:", sitkimg.GetSize())
        print("SimpleITK spacing:", sitkimg.GetSpacing())
        print("SimpleITK origin:", sitkimg.GetOrigin())
        print("SimpleITK direction:", sitkimg.GetDirection())

    return sitkimg


def sitk2vtk(
    img: sitk.Image,
    debugOn: bool = False,
    array_name: str = "values",
) -> vtk.vtkImageData:
    """
    Convert a 2D or 3D SimpleITK image into vtkImageData.

    Parameters
    ----------
    img:
        Input SimpleITK image.
    debugOn:
        Print conversion details.
    array_name:
        Name assigned to the VTK data array.

    Returns
    -------
    vtk.vtkImageData
        Converted VTK image.
    """
    if not isinstance(img, sitk.Image):
        raise TypeError("sitk2vtk expects a SimpleITK.Image.")

    if img.GetDimension() not in (2, 3):
        raise ValueError("sitk2vtk supports only 2D and 3D images.")

    size = list(img.GetSize())
    origin = list(img.GetOrigin())
    spacing = list(img.GetSpacing())
    direction = list(img.GetDirection())
    ncomp = int(img.GetNumberOfComponentsPerPixel())

    if img.GetDimension() == 2:
        size.append(1)
        origin.append(0.0)
        spacing.append(1.0)

        direction = [
            direction[0], direction[1], 0.0,
            direction[2], direction[3], 0.0,
            0.0,          0.0,          1.0,
        ]

    array = sitk.GetArrayFromImage(img)

    vtk_image = vtk.vtkImageData()
    vtk_image.SetDimensions(size)
    vtk_image.SetExtent(
        0, size[0] - 1,
        0, size[1] - 1,
        0, size[2] - 1,
    )
    vtk_image.SetSpacing(spacing)
    vtk_image.SetOrigin(origin)

    if vtk.vtkVersion.GetVTKMajorVersion() >= 9:
        vtk_image.SetDirectionMatrix(direction)
    elif debugOn:
        print("Warning: VTK < 9 cannot store a direction matrix.")

    if ncomp == 1:
        values = np.ascontiguousarray(array).ravel(order="C")
    else:
        values = np.ascontiguousarray(
            array.reshape(-1, ncomp, order="C")
        )

    vtk_array = numpy_support.numpy_to_vtk(
        values,
        deep=True,
    )
    vtk_array.SetName(array_name)

    vtk_image.GetPointData().SetScalars(vtk_array)
    vtk_image.Modified()

    if debugOn:
        print("VTK dimensions:", vtk_image.GetDimensions())
        print("VTK components:", vtk_array.GetNumberOfComponents())
        print("VTK origin:", vtk_image.GetOrigin())
        print("VTK spacing:", vtk_image.GetSpacing())

    return vtk_image


# =============================================================================
# COORDINATE TRANSFORMS
# =============================================================================


def get_voxel_to_space_matrix(
    image: sitk.Image,
    space: str = "lps",
) -> np.ndarray:
    """
    Return a 4x4 matrix mapping ITK voxel indices into a target space.

    Parameters
    ----------
    image:
        Three-dimensional SimpleITK image.
    space:
        One of "lps", "ras", "fsl", or "index".

    Returns
    -------
    np.ndarray
        4x4 affine matrix.
    """
    if image.GetDimension() != 3:
        raise ValueError(
            "Coordinate-aware ParaView export supports 3D images only."
        )

    space = str(space).lower()

    spacing = np.asarray(image.GetSpacing(), dtype=np.float64)
    origin = np.asarray(image.GetOrigin(), dtype=np.float64)
    direction = np.asarray(
        image.GetDirection(),
        dtype=np.float64,
    ).reshape(3, 3)

    voxel_to_lps = np.eye(4, dtype=np.float64)
    voxel_to_lps[:3, :3] = direction @ np.diag(spacing)
    voxel_to_lps[:3, 3] = origin

    if space == "lps":
        return voxel_to_lps

    if space == "ras":
        lps_to_ras = np.diag([-1.0, -1.0, 1.0, 1.0])
        return lps_to_ras @ voxel_to_lps

    if space == "index":
        return np.eye(4, dtype=np.float64)

    if space == "fsl":
        size = image.GetSize()

        voxel_to_fsl = np.diag(
            [
                spacing[0],
                spacing[1],
                spacing[2],
                1.0,
            ]
        )

        # FSL conditionally reverses the X axis for neurological storage.
        if np.linalg.det(voxel_to_lps[:3, :3]) > 0:
            voxel_to_fsl[0, 0] = -spacing[0]
            voxel_to_fsl[0, 3] = (size[0] - 1) * spacing[0]

        return voxel_to_fsl

    raise ValueError(
        f"Unknown coordinate space {space!r}. "
        "Choose 'lps', 'ras', 'fsl', or 'index'."
    )


def get_lps_to_space_linear_matrix(
    image: sitk.Image,
    space: str,
) -> np.ndarray:
    """
    Return the 3x3 linear transform from LPS vector components to target space.
    """
    voxel_to_lps = get_voxel_to_space_matrix(image, "lps")
    voxel_to_target = get_voxel_to_space_matrix(image, space)

    return (
        voxel_to_target[:3, :3]
        @ np.linalg.inv(voxel_to_lps[:3, :3])
    )


def transform_points(
    points_ijk: np.ndarray,
    matrix: np.ndarray,
) -> np.ndarray:
    """
    Apply a 4x4 affine matrix to an N-by-3 array of points.
    """
    points = np.asarray(points_ijk, dtype=np.float64)
    matrix = np.asarray(matrix, dtype=np.float64)

    if points.ndim != 2 or points.shape[1] != 3:
        raise ValueError("points_ijk must have shape (N, 3).")

    if matrix.shape != (4, 4):
        raise ValueError("matrix must have shape (4, 4).")

    homogeneous = np.column_stack(
        [
            points,
            np.ones(points.shape[0], dtype=np.float64),
        ]
    )

    return (homogeneous @ matrix.T)[:, :3]


