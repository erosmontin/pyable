# TENSOR HELPERS
# =============================================================================


def _tensor_components_to_matrices(values: np.ndarray) -> np.ndarray:
    """
    Convert tensor components into N-by-3-by-3 matrices.

    Supported layouts
    -----------------
    6 components:
        XX, XY, XZ, YY, YZ, ZZ

    9 components:
        Full row-major 3x3 matrix.
    """
    values = np.asarray(values)

    if values.ndim != 2:
        raise ValueError("Tensor values must have shape (N, components).")

    ncomp = values.shape[1]

    if ncomp == 9:
        return values.reshape(-1, 3, 3)

    if ncomp == 6:
        xx, xy, xz, yy, yz, zz = values.T

        tensors = np.empty(
            (values.shape[0], 3, 3),
            dtype=values.dtype,
        )

        tensors[:, 0, 0] = xx
        tensors[:, 0, 1] = xy
        tensors[:, 0, 2] = xz

        tensors[:, 1, 0] = xy
        tensors[:, 1, 1] = yy
        tensors[:, 1, 2] = yz

        tensors[:, 2, 0] = xz
        tensors[:, 2, 1] = yz
        tensors[:, 2, 2] = zz

        return tensors

    raise ValueError(
        "Tensor data must contain either 6 symmetric components "
        "or 9 full components."
    )


