def write_vtk_dataset(dataset, output_path) -> str:
    """
    Write a VTK dataset using the correct XML writer.

    Supported outputs
    -----------------
    .vts:
        vtkStructuredGrid

    .vtp:
        vtkPolyData

    .vtm:
        vtkMultiBlockDataSet
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    suffix = output_path.suffix.lower()

    if suffix == ".vts":
        if not isinstance(dataset, vtk.vtkStructuredGrid):
            raise TypeError(".vts requires vtkStructuredGrid.")
        writer = vtk.vtkXMLStructuredGridWriter()

    elif suffix == ".vtp":
        if not isinstance(dataset, vtk.vtkPolyData):
            raise TypeError(".vtp requires vtkPolyData.")
        writer = vtk.vtkXMLPolyDataWriter()

    elif suffix == ".vtm":
        if not isinstance(dataset, vtk.vtkMultiBlockDataSet):
            raise TypeError(".vtm requires vtkMultiBlockDataSet.")
        writer = vtk.vtkXMLMultiBlockDataWriter()

    else:
        raise ValueError(
            "Unsupported extension. Use .vts, .vtp, or .vtm."
        )

    writer.SetFileName(str(output_path))
    writer.SetInputData(dataset)

    if writer.Write() != 1:
        raise IOError(f"Could not write VTK file: {output_path}")

    return str(output_path)
