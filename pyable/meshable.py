def binary_mask_to_polydata(
    image: sitk.Image,
    space: str = "lps",
    level: float = 0.5,
    smooth_iterations: int = 0,
    relaxation_factor: float = 0.1,
) -> vtk.vtkPolyData:
    """
    Convert a binary SimpleITK mask into a coordinate-aware surface mesh.

    Parameters
    ----------
    image:
        3D binary mask. Every value greater than zero is foreground.
    space:
        "lps", "ras", "fsl", or "index".
    level:
        Isosurface value.
    smooth_iterations:
        Number of optional windowed-sinc smoothing iterations.
        Use 0 to disable smoothing.
    relaxation_factor:
        Smoothing relaxation factor.

    Returns
    -------
    vtk.vtkPolyData
        Surface mesh.
    """
    if image.GetDimension() != 3:
        raise ValueError("binary_mask_to_polydata supports 3D masks only.")

    try:
        from skimage.measure import marching_cubes
    except ImportError as exc:
        raise ImportError(
            "scikit-image is required for surface export: "
            "pip install scikit-image"
        ) from exc

    mask = sitk.GetArrayFromImage(image) > 0

    if not np.any(mask):
        raise ValueError("Cannot create a surface from an empty mask.")

    padded = np.pad(
        mask.astype(np.uint8),
        pad_width=1,
        mode="constant",
        constant_values=0,
    )

    vertices_zyx, faces, _, _ = marching_cubes(
        padded,
        level=level,
    )

    # Remove the one-voxel padding offset.
    vertices_zyx -= 1.0

    # skimage returns ZYX vertices. Convert to ITK IJK = XYZ.
    vertices_ijk = vertices_zyx[:, [2, 1, 0]]

    voxel_to_output = get_voxel_to_space_matrix(image, space)
    vertices_xyz = transform_points(vertices_ijk, voxel_to_output)

    vtk_points = vtk.vtkPoints()
    vtk_points.SetData(
        numpy_support.numpy_to_vtk(
            np.ascontiguousarray(
                vertices_xyz,
                dtype=np.float32,
            ),
            deep=True,
        )
    )

    vtk_faces = vtk.vtkCellArray()

    for face in faces:
        triangle = vtk.vtkTriangle()
        triangle.GetPointIds().SetId(0, int(face[0]))
        triangle.GetPointIds().SetId(1, int(face[1]))
        triangle.GetPointIds().SetId(2, int(face[2]))
        vtk_faces.InsertNextCell(triangle)

    polydata = vtk.vtkPolyData()
    polydata.SetPoints(vtk_points)
    polydata.SetPolys(vtk_faces)

    clean = vtk.vtkCleanPolyData()
    clean.SetInputData(polydata)
    clean.Update()

    current_output = clean.GetOutput()

    if smooth_iterations > 0:
        smoother = vtk.vtkSmoothPolyDataFilter()
        smoother.SetInputData(current_output)
        smoother.SetNumberOfIterations(int(smooth_iterations))
        smoother.SetRelaxationFactor(float(relaxation_factor))
        smoother.FeatureEdgeSmoothingOff()
        smoother.BoundarySmoothingOn()
        smoother.Update()
        current_output = smoother.GetOutput()

    normals = vtk.vtkPolyDataNormals()
    normals.SetInputData(current_output)
    normals.AutoOrientNormalsOn()
    normals.ConsistencyOn()
    normals.SplittingOff()
    normals.Update()

    output = vtk.vtkPolyData()
    output.ShallowCopy(normals.GetOutput())
    return output


def label_map_to_multiblock(
    image: sitk.Image,
    labels: Optional[Sequence[int]] = None,
    space: str = "lps",
    smooth_iterations: int = 0,
    relaxation_factor: float = 0.1,
) -> vtk.vtkMultiBlockDataSet:
    """
    Convert a multi-label segmentation into one VTK surface per label.

    Parameters
    ----------
    image:
        Integer 3D label image.
    labels:
        Labels to export. If None, every non-zero label is exported.
    space:
        "lps", "ras", "fsl", or "index".
    smooth_iterations:
        Optional surface smoothing iterations.
    relaxation_factor:
        Optional surface smoothing relaxation factor.

    Returns
    -------
    vtk.vtkMultiBlockDataSet
        One vtkPolyData block per label.
    """
    if image.GetDimension() != 3:
        raise ValueError("label_map_to_multiblock supports 3D images only.")

    array = sitk.GetArrayFromImage(image)

    if labels is None:
        labels = [
            int(value)
            for value in np.unique(array)
            if int(value) != 0
        ]
    else:
        labels = [int(value) for value in labels if int(value) != 0]

    output = vtk.vtkMultiBlockDataSet()
    output.SetNumberOfBlocks(len(labels))

    for block_index, label_value in enumerate(labels):
        label_mask = sitk.Cast(
            sitk.Equal(image, label_value),
            sitk.sitkUInt8,
        )

        if sitk.GetArrayViewFromImage(label_mask).max() == 0:
            continue

        surface = binary_mask_to_polydata(
            label_mask,
            space=space,
            smooth_iterations=smooth_iterations,
            relaxation_factor=relaxation_factor,
        )

        label_array = numpy_support.numpy_to_vtk(
            np.full(
                surface.GetNumberOfPoints(),
                label_value,
                dtype=np.int32,
            ),
            deep=True,
        )
        label_array.SetName("label")
        surface.GetPointData().AddArray(label_array)

        output.SetBlock(block_index, surface)
        output.GetMetaData(block_index).Set(
            vtk.vtkCompositeDataSet.NAME(),
            f"label_{label_value}",
        )

    return output


