def sitk_to_structured_grid(
    image: sitk.Image,
    space: str = "lps",
    stride: int = 1,
    array_name: str = "values",
    data_role: str = "scalars",
) -> vtk.vtkStructuredGrid:
    """
    Convert a 3D SimpleITK image into a coordinate-aware VTK structured grid.

    Parameters
    ----------
    image:
        Input 3D SimpleITK image.
    space:
        "lps", "ras", "fsl", or "index".
    stride:
        Spatial sampling step. A stride of 2 keeps every second voxel.
    array_name:
        Name assigned to the VTK data array.
    data_role:
        "scalars", "vectors", or "tensors".

    Returns
    -------
    vtk.vtkStructuredGrid
        ParaView-compatible structured grid.
    """
    if image.GetDimension() != 3:
        raise ValueError("Only 3D images are supported.")

    stride = max(1, int(stride))
    data_role = str(data_role).lower()

    if data_role not in {"scalars", "vectors", "tensors"}:
        raise ValueError(
            "data_role must be 'scalars', 'vectors', or 'tensors'."
        )

    array = sitk.GetArrayFromImage(image)

    if array.ndim not in (3, 4):
        raise ValueError(
            f"Unsupported array shape {array.shape}. "
            "Expected ZYX or ZYXC."
        )

    array = array[
        ::stride,
        ::stride,
        ::stride,
        ...,
    ]

    nz, ny, nx = array.shape[:3]

    i, j, k = np.meshgrid(
        np.arange(nx, dtype=np.float64) * stride,
        np.arange(ny, dtype=np.float64) * stride,
        np.arange(nz, dtype=np.float64) * stride,
        indexing="ij",
    )

    ijk = np.column_stack(
        [
            i.ravel(order="F"),
            j.ravel(order="F"),
            k.ravel(order="F"),
        ]
    )

    voxel_to_output = get_voxel_to_space_matrix(image, space)
    output_points = transform_points(ijk, voxel_to_output)

    vtk_points = vtk.vtkPoints()
    vtk_points.SetData(
        numpy_support.numpy_to_vtk(
            np.ascontiguousarray(
                output_points,
                dtype=np.float32,
            ),
            deep=True,
        )
    )

    grid = vtk.vtkStructuredGrid()
    grid.SetDimensions(nx, ny, nz)
    grid.SetPoints(vtk_points)

    # Scalar image: array shape is ZYX.
    if array.ndim == 3:
        if data_role != "scalars":
            raise ValueError(
                "A scalar image must use data_role='scalars'."
            )

        values = np.ascontiguousarray(
            array.ravel(order="C")
        )

        vtk_values = numpy_support.numpy_to_vtk(
            values,
            deep=True,
        )
        vtk_values.SetName(array_name)

        grid.GetPointData().SetScalars(vtk_values)

    # Multi-component image: array shape is ZYXC.
    else:
        ncomp = int(array.shape[-1])

        values = np.ascontiguousarray(
            array.reshape(-1, ncomp, order="C")
        )

        if data_role == "vectors":
            if ncomp != 3:
                raise ValueError(
                    "Vector data must have exactly 3 components."
                )

            if str(space).lower() != "lps":
                linear = get_lps_to_space_linear_matrix(
                    image,
                    space,
                )
                values = np.ascontiguousarray(
                    values @ linear.T
                )

            vtk_values = numpy_support.numpy_to_vtk(
                values,
                deep=True,
            )
            vtk_values.SetName(array_name)

            grid.GetPointData().SetVectors(vtk_values)

        elif data_role == "tensors":
            tensors = _tensor_components_to_matrices(values)

            if str(space).lower() != "lps":
                linear = get_lps_to_space_linear_matrix(
                    image,
                    space,
                )

                tensors = (
                    linear[None, :, :]
                    @ tensors
                    @ linear.T[None, :, :]
                )

            tensor_values = np.ascontiguousarray(
                tensors.reshape(-1, 9)
            )

            vtk_values = numpy_support.numpy_to_vtk(
                tensor_values,
                deep=True,
            )
            vtk_values.SetName(array_name)

            grid.GetPointData().SetTensors(vtk_values)

        else:
            vtk_values = numpy_support.numpy_to_vtk(
                values,
                deep=True,
            )
            vtk_values.SetName(array_name)

            grid.GetPointData().SetScalars(vtk_values)

    grid.Modified()
    return grid


